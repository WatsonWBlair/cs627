"""
PyTorch Dataset for loading pre-generated encoder tokens.

This dataset loads tokens from HDF5 files generated by pregenerate_tokens.py,
enabling fast adapter training without encoder forward passes.

Features:
- Memory-mapped HDF5 access for large datasets
- Configurable token sources (single encoder, matched pairs, mixed)
- Optional caching for frequently accessed samples
- Support for cross-modal and reconstruction training
"""

import h5py
import torch
import numpy as np
from torch.utils.data import Dataset
from typing import Dict, List, Optional, Tuple, Union
from pathlib import Path
import json


class TokenDataset(Dataset):
    """
    Dataset for loading pre-generated encoder tokens from HDF5 files.
    
    Args:
        h5_path: Path to HDF5 file containing tokens
        encoders: List of encoder names to load (None = all)
        cache_size: Number of samples to cache in memory (0 = no cache)
        token_mode: How to select tokens ('single', 'matched', 'mixed')
        primary_encoder: Primary encoder for 'single' mode
    """
    
    def __init__(
        self,
        h5_path: str,
        encoders: Optional[List[str]] = None,
        cache_size: int = 0,
        token_mode: str = 'matched',
        primary_encoder: Optional[str] = None
    ):
        self.h5_path = Path(h5_path)
        self.token_mode = token_mode
        self.primary_encoder = primary_encoder
        
        if not self.h5_path.exists():
            raise FileNotFoundError(f"Token file not found: {h5_path}")
        
        # Open H5 file for reading metadata
        with h5py.File(self.h5_path, 'r') as f:
            self.num_samples = f.attrs['num_samples']
            self.token_dim = f.attrs['token_dim']
            available_encoders = list(f.attrs['encoders'])
            
            # Select encoders to use
            if encoders is None:
                self.encoders = available_encoders
            else:
                # Validate requested encoders
                for enc in encoders:
                    if enc not in available_encoders:
                        raise ValueError(f"Encoder '{enc}' not found in {h5_path}")
                self.encoders = encoders
            
            # Load segment IDs and labels
            self.segment_ids = [s.decode('utf-8') for s in f['segment_ids'][:]]
            self.labels = f['labels'][:]
        
        # Validate token mode configuration
        if token_mode == 'single' and primary_encoder is None:
            raise ValueError("primary_encoder must be specified for 'single' mode")
        if primary_encoder and primary_encoder not in self.encoders:
            raise ValueError(f"Primary encoder '{primary_encoder}' not in available encoders")
        
        # Initialize cache
        self.cache_size = min(cache_size, self.num_samples)
        self.cache = {} if cache_size > 0 else None
        
        # Keep file handle open for efficient access
        self.h5_file = None
        self._open_file()
    
    def _open_file(self):
        """Open H5 file for reading."""
        if self.h5_file is None:
            self.h5_file = h5py.File(self.h5_path, 'r', swmr=True)
    
    def __len__(self) -> int:
        return self.num_samples
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Get tokens for a sample.
        
        Returns:
            Dictionary containing:
            - 'tokens': Dict of encoder_name -> token tensor
            - 'segment_id': Segment identifier
            - 'label': Ground truth label
            - 'source_token': Primary token (for decoder training)
            - 'target_tokens': Target tokens (for reconstruction)
        """
        # Check cache
        if self.cache is not None and idx in self.cache:
            return self.cache[idx]
        
        # Load tokens from H5
        self._open_file()
        
        tokens = {}
        for encoder in self.encoders:
            token = self.h5_file[encoder][idx]
            tokens[encoder] = torch.from_numpy(token).float()
        
        # Prepare output based on token mode
        sample = {
            'tokens': tokens,
            'segment_id': self.segment_ids[idx],
            'label': torch.tensor(self.labels[idx], dtype=torch.float32)
        }
        
        if self.token_mode == 'single':
            # Use only primary encoder token
            sample['source_token'] = tokens[self.primary_encoder]
            sample['target_tokens'] = None
            
        elif self.token_mode == 'matched':
            # All tokens from same segment (for cross-modal training)
            sample['source_token'] = None
            sample['target_tokens'] = tokens
            
        elif self.token_mode == 'mixed':
            # Mix tokens from different modalities
            # Useful for robustness training
            sample['source_token'] = None
            sample['target_tokens'] = tokens
        
        # Add to cache if enabled
        if self.cache is not None and len(self.cache) < self.cache_size:
            self.cache[idx] = sample
        
        return sample
    
    def __del__(self):
        """Clean up H5 file handle."""
        if self.h5_file is not None:
            self.h5_file.close()
    
    def get_encoder_names(self) -> List[str]:
        """Get list of available encoder names."""
        return self.encoders
    
    def get_token_dim(self) -> int:
        """Get dimension of token vectors."""
        return self.token_dim


class MultiDatasetTokenLoader(Dataset):
    """
    Combines multiple token datasets for training across different data sources.
    
    Args:
        dataset_configs: List of (h5_path, weight) tuples
        **kwargs: Additional arguments passed to TokenDataset
    """
    
    def __init__(
        self,
        dataset_configs: List[Tuple[str, float]],
        **kwargs
    ):
        self.datasets = []
        self.weights = []
        self.cumulative_sizes = []
        
        total_size = 0
        for h5_path, weight in dataset_configs:
            dataset = TokenDataset(h5_path, **kwargs)
            self.datasets.append(dataset)
            self.weights.append(weight)
            
            total_size += len(dataset)
            self.cumulative_sizes.append(total_size)
        
        # Normalize weights
        total_weight = sum(self.weights)
        self.weights = [w / total_weight for w in self.weights]
    
    def __len__(self) -> int:
        return self.cumulative_sizes[-1]
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Get sample from appropriate dataset.
        """
        # Find which dataset this index belongs to
        dataset_idx = 0
        local_idx = idx
        
        for i, cumsum in enumerate(self.cumulative_sizes):
            if idx < cumsum:
                dataset_idx = i
                if i > 0:
                    local_idx = idx - self.cumulative_sizes[i - 1]
                break
        
        sample = self.datasets[dataset_idx][local_idx]
        sample['dataset_idx'] = dataset_idx
        sample['dataset_weight'] = self.weights[dataset_idx]
        
        return sample


def create_token_dataloader(
    split: str,
    token_dir: str = 'data/pregenerated_tokens/mosi',
    batch_size: int = 32,
    shuffle: bool = True,
    token_mode: str = 'matched',
    encoders: Optional[List[str]] = None,
    cache_size: int = 1000,
    num_workers: int = 0
) -> torch.utils.data.DataLoader:
    """
    Convenience function to create a DataLoader for token training.
    
    Args:
        split: Dataset split ('train', 'val', 'test')
        token_dir: Directory containing token H5 files
        batch_size: Batch size for training
        shuffle: Whether to shuffle data
        token_mode: Token selection mode
        encoders: List of encoders to use
        cache_size: Number of samples to cache
        num_workers: Number of data loading workers
    
    Returns:
        DataLoader for token training
    """
    token_path = Path(token_dir) / f"{split}_tokens.h5"
    
    dataset = TokenDataset(
        h5_path=str(token_path),
        encoders=encoders,
        cache_size=cache_size,
        token_mode=token_mode
    )
    
    def collate_fn(batch: List[Dict]) -> Dict[str, torch.Tensor]:
        """Custom collate function for token batches."""
        # Stack tokens for each encoder
        collated = {
            'segment_ids': [s['segment_id'] for s in batch],
            'labels': torch.stack([s['label'] for s in batch])
        }
        
        # Handle tokens based on mode
        if token_mode == 'single':
            collated['source_tokens'] = torch.stack([s['source_token'] for s in batch])
        else:
            # Stack tokens for each encoder
            encoder_names = batch[0]['tokens'].keys()
            collated['tokens'] = {}
            for encoder in encoder_names:
                collated['tokens'][encoder] = torch.stack([
                    s['tokens'][encoder] for s in batch
                ])
        
        return collated
    
    return torch.utils.data.DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        collate_fn=collate_fn,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available()
    )


def load_token_metadata(token_dir: str = 'data/pregenerated_tokens/mosi') -> Dict:
    """
    Load metadata about pre-generated tokens.
    
    Args:
        token_dir: Directory containing token files and metadata
    
    Returns:
        Dictionary with metadata about tokens
    """
    metadata_path = Path(token_dir) / 'metadata.json'
    
    if not metadata_path.exists():
        raise FileNotFoundError(f"Metadata file not found: {metadata_path}")
    
    with open(metadata_path, 'r') as f:
        metadata = json.load(f)
    
    return metadata